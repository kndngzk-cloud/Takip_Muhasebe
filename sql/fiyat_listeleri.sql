-- Uygulandi: fiyat listeleri (v2.00)
-- fiyat_listeleri: listenin adi ve odeme secenekleri (secenekler = [{k, ad}], sirasiyla kolonlar)
-- fiyat_listesi_kalemleri: listedeki urun ve her secenek icin fiyat (fiyatlar = {k: fiyat})
create table if not exists public.fiyat_listeleri (
  id bigint generated by default as identity primary key,
  ad text not null,
  aciklama text,
  para_birimi text not null default 'TRY',
  kdv_dahil boolean not null default true,
  secenekler jsonb not null default '[{"k":"pesin","ad":"Peşin"},{"k":"kk1","ad":"Kredi kartı tek çekim"},{"k":"kk3","ad":"Kredi kartı 3 taksit"},{"k":"kk5","ad":"Kredi kartı 5 taksit"},{"k":"cek","ad":"Çek"}]'::jsonb,
  sira integer not null default 0,
  olusturma timestamptz not null default now(),
  guncelleme timestamptz not null default now()
);

create table if not exists public.fiyat_listesi_kalemleri (
  id bigint generated by default as identity primary key,
  liste_id bigint not null references public.fiyat_listeleri(id) on delete cascade,
  urun_id bigint not null references public.urunler(id) on delete cascade,
  fiyatlar jsonb not null default '{}'::jsonb,
  sira integer not null default 0,
  olusturma timestamptz not null default now(),
  unique (liste_id, urun_id)
);
create index if not exists fiyat_listesi_kalemleri_liste_idx on public.fiyat_listesi_kalemleri(liste_id);
create index if not exists fiyat_listesi_kalemleri_urun_idx on public.fiyat_listesi_kalemleri(urun_id);

alter table public.fiyat_listeleri enable row level security;
alter table public.fiyat_listesi_kalemleri enable row level security;

create policy "okuma" on public.fiyat_listeleri for select to authenticated using (true);
create policy "ekleme" on public.fiyat_listeleri for insert to authenticated with check (true);
create policy "guncelleme" on public.fiyat_listeleri for update to authenticated using (true) with check (true);
create policy "admin silme" on public.fiyat_listeleri for delete to authenticated using ((select private.is_admin()));

create policy "okuma" on public.fiyat_listesi_kalemleri for select to authenticated using (true);
create policy "ekleme" on public.fiyat_listesi_kalemleri for insert to authenticated with check (true);
create policy "guncelleme" on public.fiyat_listesi_kalemleri for update to authenticated using (true) with check (true);
create policy "silme" on public.fiyat_listesi_kalemleri for delete to authenticated using (true);

grant select, insert, update, delete on public.fiyat_listeleri, public.fiyat_listesi_kalemleri to authenticated;
